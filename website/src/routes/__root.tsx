import {
  Outlet,
  Link,
  createRootRouteWithContext,
  useRouter,
  HeadContent,
  Scripts,
} from "@tanstack/react-router";
import { useEffect, type ReactNode } from "react";

import appCss from "../styles.css?url";
import { reportLovableError } from "../lib/lovable-error-reporting";
import { supabase } from "@/integrations/supabase/client";
import { SiteHeader } from "@/components/site-header";
import { SiteFooter } from "@/components/site-footer";

function NotFoundComponent() {
  return (
    <div className="relative flex min-h-screen items-center justify-center overflow-hidden px-4">
      <div className="aurora-glow" />
      <div className="relative max-w-md text-center">
        <p className="text-aurora text-8xl font-bold tracking-tight">404</p>
        <h2 className="mt-4 text-xl font-semibold text-text-primary">Off the map</h2>
        <p className="mt-2 text-sm text-text-secondary">
          That page has drifted beyond the aurora. Head back home.
        </p>
        <Link
          to="/"
          className="bg-aurora mt-6 inline-flex items-center justify-center rounded-full px-5 py-2 text-sm font-medium text-deep-space transition-transform hover:-translate-y-0.5"
        >
          Return home
        </Link>
      </div>
    </div>
  );
}

function ErrorComponent({ error, reset }: { error: Error; reset: () => void }) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);

  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-xl font-semibold tracking-tight text-text-primary">
          Something drifted off course
        </h1>
        <p className="mt-2 text-sm text-text-secondary">Try again or head back home.</p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="bg-aurora inline-flex items-center justify-center rounded-full px-4 py-2 text-sm font-medium text-deep-space"
          >
            Try again
          </button>
          <a
            href="/"
            className="inline-flex items-center justify-center rounded-full border border-white/10 px-4 py-2 text-sm font-medium text-text-primary transition-colors hover:border-aurora-teal/40"
          >
            Go home
          </a>
        </div>
      </div>
    </div>
  );
}

